-- 1. DROP EXISTING TABLES IF RE-RUNNING
DROP TABLE IF EXISTS public.notifications CASCADE;
DROP TABLE IF EXISTS public.weekly_reports CASCADE;
DROP TABLE IF EXISTS public.daily_logs CASCADE;
DROP TABLE IF EXISTS public.attendance CASCADE;
DROP TABLE IF EXISTS public.students CASCADE;

-- 2. CREATE TABLE: students
CREATE TABLE public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number TEXT UNIQUE NOT NULL CHECK (matric_number ~ '^MOUAU/CMP/[0-9]{2}/[0-9]{6}$'),
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    department TEXT NOT NULL DEFAULT 'Computer Science',
    level TEXT NOT NULL DEFAULT '300 Level',
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    company_name TEXT NOT NULL,
    office_address TEXT NOT NULL,
    office_lat DOUBLE PRECISION NOT NULL,
    office_lon DOUBLE PRECISION NOT NULL,
    geofence_radius INTEGER NOT NULL DEFAULT 100,
    industry_supervisor_name TEXT NOT NULL,
    industry_supervisor_phone TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. CREATE TABLE: attendance
CREATE TABLE public.attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number TEXT NOT NULL REFERENCES public.students(matric_number) ON DELETE CASCADE,
    attendance_date DATE NOT NULL DEFAULT CURRENT_DATE,
    clock_in_time TEXT,
    clock_in_distance DOUBLE PRECISION,
    clock_in_status TEXT CHECK (clock_in_status IN ('On-Time', 'Late')),
    clock_in_selfie_url TEXT,
    clock_out_time TEXT,
    clock_out_distance DOUBLE PRECISION,
    clock_out_selfie_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(matric_number, attendance_date)
);

-- 4. CREATE TABLE: daily_logs
CREATE TABLE public.daily_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number TEXT NOT NULL REFERENCES public.students(matric_number) ON DELETE CASCADE,
    log_date DATE NOT NULL DEFAULT CURRENT_DATE,
    work_description TEXT NOT NULL,
    tools_used TEXT NOT NULL,
    hours_worked NUMERIC(4,1) NOT NULL DEFAULT 8,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Verified', 'Approved', 'Rejected')),
    supervisor_feedback TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. CREATE TABLE: weekly_reports
CREATE TABLE public.weekly_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number TEXT NOT NULL REFERENCES public.students(matric_number) ON DELETE CASCADE,
    week_number INTEGER NOT NULL CHECK (week_number BETWEEN 1 AND 24),
    summary TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Submitted' CHECK (status IN ('Pending', 'Submitted', 'Verified', 'Approved')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    UNIQUE(matric_number, week_number)
);

-- 6. CREATE TABLE: notifications
CREATE TABLE public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_role TEXT NOT NULL DEFAULT 'admin',
    matric_number TEXT,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. DISABLE ROW LEVEL SECURITY FOR CLIENT SDK OPERATIONS
ALTER TABLE public.students DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.daily_logs DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.weekly_reports DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications DISABLE ROW LEVEL SECURITY;

-- 8. CREATE PUBLIC STORAGE BUCKET: selfies
INSERT INTO storage.buckets (id, name, public)
VALUES ('selfies', 'selfies', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Public Read Access for Selfies" ON storage.objects;
CREATE POLICY "Public Read Access for Selfies"
ON storage.objects FOR SELECT
USING (bucket_id = 'selfies');

DROP POLICY IF EXISTS "Public Upload Access for Selfies" ON storage.objects;
CREATE POLICY "Public Upload Access for Selfies"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'selfies');

DROP POLICY IF EXISTS "Public Update Access for Selfies" ON storage.objects;
CREATE POLICY "Public Update Access for Selfies"
ON storage.objects FOR UPDATE
USING (bucket_id = 'selfies');

